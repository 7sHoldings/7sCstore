/** Tank's nominal capacity (top of the chart). */
export const TANK_CAPACITY = GAL[GAL.length - 1];
export const TANK_MAX_INCHES = GAL.length * STEP;

/** Convert a stick reading in inches to gallons (linear interpolation). */
export function gallonsForInches(inches: number): number {
  if (!isFinite(inches) || inches <= 0) return 0;
  if (inches >= TANK_MAX_INCHES) return GAL[GAL.length - 1];
  const idx = inches / STEP - 1; // float index into GAL
  if (idx <= 0) return Math.round(GAL[0] * (inches / STEP) * 100) / 100; // 0..0.25"
  const lo = Math.floor(idx);
  const hi = Math.ceil(idx);
  const val = lo === hi ? GAL[lo] : GAL[lo] + (GAL[hi] - GAL[lo]) * (idx - lo);
  return Math.round(val * 100) / 100;
}
